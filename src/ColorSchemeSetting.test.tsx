import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import { ColorSchemeSetting } from './ColorSchemeSetting';
import { COLOR_SCHEME_KEY } from './lib/color-scheme';
let host: HTMLDivElement, root: Root;
beforeEach(() => { (globalThis as any).IS_REACT_ACT_ENVIRONMENT = true; localStorage.clear(); vi.stubGlobal('matchMedia', vi.fn(() => ({ matches: false, addEventListener: vi.fn(), removeEventListener: vi.fn() }))); host = document.createElement('div'); root = createRoot(host); });
afterEach(async () => { await act(async () => root.unmount()); vi.unstubAllGlobals(); localStorage.clear(); delete document.documentElement.dataset.colorScheme; });
it('offers light, dark and follow-system as one labelled group, keeps two copies in sync and sends no request', async () => {
  const fetchSpy = vi.spyOn(globalThis, 'fetch');
  await act(async () => root.render(<><ColorSchemeSetting /><ColorSchemeSetting /></>));
  const groups = host.querySelectorAll('fieldset.color-scheme-setting');
  expect(groups).toHaveLength(2); expect(groups[0].querySelector('legend')?.textContent).toBe('配色');
  expect([...groups[0].querySelectorAll('label')].map(label => label.textContent)).toEqual(['浅色', '深色', '跟随系统']);
  expect(groups[0].querySelector<HTMLInputElement>('input[value=light]')!.checked).toBe(true);
  await act(async () => groups[0].querySelector<HTMLInputElement>('input[value=dark]')!.click());
  expect(localStorage.getItem(COLOR_SCHEME_KEY)).toBe('dark'); expect(document.documentElement.dataset.colorScheme).toBe('dark');
  expect(groups[1].querySelector<HTMLInputElement>('input[value=dark]')!.checked).toBe(true);
  expect(fetchSpy).not.toHaveBeenCalled();
});
